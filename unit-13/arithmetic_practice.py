boys = 25
girls = 22
absent = 6
price_per_book = 1500
books = 4
bill = 6000
friends = 4
students = 47
group_size = 5
side = 12

print("Addition (total students):", boys + girls)
print("Subtraction (students present):", (boys + girls) - absent)
print("Multiplication (cost of books):", price_per_book * books)
print("Division (each friend pays):", bill / friends)
print("Floor division (full groups):", students // group_size)
print("Modulus (students left over):", students % group_size)
print("Exponent (area of a square):", side ** 2)
